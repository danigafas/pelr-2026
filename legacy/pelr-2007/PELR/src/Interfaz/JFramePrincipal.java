    private void bAddCadenaKCMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_bAddCadenaKCMouseClicked
        if (tbAddCadenaKC.getText()!="") {
            Estado etemp = new Estado();
            Vector aux = new Vector();
            Vector aux2 = new Vector();
            String simbActual,cadActual,nombreEstado;
            boolean reconocida=false;

            aux2 = a.getSimbolos();
            nombreEstado = "";
            cadActual = tbAddCadenaKC.getText();
            etemp = a.obtenerEstado(0);
            if (cadActual.equals("%")) {
                int indice = a.buscarEstado(etemp);
                a.obtenerEstado(indice).putTipoEstado("INICIAL/FINAL");
            }
            else {
                for (int i=0; i<tbAddCadenaKC.getText().length(); i++) {
                    simbActual = cadActual.substring(0,1);
                    nombreEstado = nombreEstado + simbActual;
                    cadActual = cadActual.substring(1);
                    try {
                        aux = (Vector)a.getTransicion(a.buscarEstado(etemp),aux2.indexOf(simbActual));
                        etemp = (Estado)aux.elementAt(0);
                        if (etemp.getTipoEstado().equals("FINAL")) reconocida=true;
                        else reconocida=false;
                    }
                    catch (Exception err) {
                        if (nombreEstado.equals(tbAddCadenaKC.getText())) {
                            Estado et = new Estado(nombreEstado,"FINAL");
                            a.addEstado(et);
                            if (!aux2.contains(simbActual)) {
                                aux2.addElement(simbActual);
                                a.addSimbolo(simbActual);
                            }
                            a.addTransicion(a.buscarEstado(etemp),aux2.indexOf(simbActual),et);
                            try {
                                aux = (Vector)a.getTransicion(a.buscarEstado(etemp),aux2.indexOf(simbActual));
                            }
                            catch(Exception err2) {}
                            etemp = (Estado)aux.elementAt(0);
                        }
                        else {
                            Estado et = new Estado(nombreEstado,"INTERMEDIO");
                            a.addEstado(et);
                            if (!aux2.contains(simbActual)) {
                                aux2.addElement(simbActual);
                                a.addSimbolo(simbActual);
                            }
                            a.addTransicion(a.buscarEstado(etemp),aux2.indexOf(simbActual),et);
                            try {
                                aux = (Vector)a.getTransicion(a.buscarEstado(etemp),aux2.indexOf(simbActual));
                            }
                            catch(Exception err2){}
                            etemp = (Estado)aux.elementAt(0);
                        }
                        reconocida=false;
                    }
                }
                if (!etemp.getTipoEstado().equals("FINAL")) {
                    int indice = a.buscarEstado(etemp);
                    a.obtenerEstado(indice).putTipoEstado("FINAL");
                }
            }
            if (reconocida) JOptionPane.showMessageDialog(null,"La cadena ya es reconocida por el automata","KC Incremental",JOptionPane.INFORMATION_MESSAGE);
            else { 
                JOptionPane.showMessageDialog(null,"Nueva cadena añadida","KC Incremental",JOptionPane.INFORMATION_MESSAGE);
                if (!minc.contains(tbAddCadenaKC.getText())) minc.addElement(tbAddCadenaKC.getText());
            }

            a = AlgoritmoKC.ejecutar(a,cbSelAlg.getSelectedIndex(),Integer.decode(cbValoresK.getSelectedItem().toString()).intValue(),mneg);
            tbAddCadenaKC.setText("");
	    tbAddCadenaKC.requestFocus();
            actualizaMInc();
            mostrarResultados();
        }
    }//GEN-LAST:event_bAddCadenaKCMouseClicked

