    /**
     *  Funcion para ordenar un vector de string. 
     *  Necesita un vector y devuelve un vector ordenado.  
     */
    private Vector ordenaVector(Vector v) {
        String t;
        for (int i=0; i<v.size(); i++)
            for (int j=i; j<v.size(); j++) {
                if (v.elementAt(i).toString().length()>v.elementAt(j).toString().length()) {
                    t = v.elementAt(i).toString();
                    v.setElementAt(v.elementAt(j).toString(),i);
                    v.setElementAt(t,j);
                }
            }
        return v;
    }
    
    /**
     *  Funcion que genera el arbol de prefijos para la muestra dada. No necesita
     *      parametros (los coge directamente de los componentes).
     *  No devuelve nada. El resultado se almacena en la variable global que contendra
     *      al automata (en este caso "a").
    */
    private void generaAP() {
        Vector est = new Vector();
        Vector est2 = new Vector();
        Vector n = new Vector();
        Vector simb = new Vector();
        boolean esta = false;
        
        // Si el estado lambda (%) no esta ya en la muestra lo añadimos. Lambda 
        //  se añade en dos casos: al generar los valores de S y aqui, por eso es
        //  necesario comprobar que no este en el vector.
        if (!mpos.contains("%")) {
            mpos.add(0,"%");
            esta = false;
        }
        else esta = true;

        // Genera todos los estados del automata. Añade los que aparecen en la 
        //      muestra y crea todos los estados intermedios.
        for (int i=0; i<mpos.size(); i++)
        {
            if (mpos.get(i).toString().length()==1) {
                est.addElement(mpos.get(i)); 
                if (!mpos.get(i).equals("%")) simb.addElement(mpos.get(i));
            }
            else 
            {
                for (int t=1; t<=mpos.get(i).toString().length(); t++)
                {
                    String temp = mpos.get(i).toString().substring(0,t);
                    if (est.contains(temp)==false) 
                        est.addElement(temp);
                }
                for (int t=0; t<mpos.get(i).toString().length(); t++) {
                    String temp = mpos.get(i).toString().substring(t,t+1);
                    if (!simb.contains(temp)) simb.addElement(temp);
                }
            }
        }
        // Ordenacion por Burbuja del vector de estados.
        est = ordenaVector(est);
        // Añadimos el tipo de estado.
        for (int i=0; i<est.size(); i++) {
            n.add(est.elementAt(i));
            if (mpos.contains(est.elementAt(i))) {
                if (est.elementAt(i).equals("%")) {
                    if (esta) est2.addElement(new Estado(n,"INICIAL/FINAL"));
                    else est2.addElement(new Estado(n,"INICIAL"));
                }
                else est2.addElement(new Estado(n,"FINAL"));
            }
            else est2.addElement(new Estado(n,"INTERMEDIO"));
            n.removeAllElements();
        }

        ap.putVectorEstados(est2);
        ap.putAlfEntrada(mpos);
        ap.putSimbolos(simb);
        ap.limpiaTransiciones();
        
        // Con esto generamos las transiciones iniciales
        String estadoActual,s;
        int indexEstado;
        for (int i=1; i<ap.obtenerNumeroEstados(); i++) {
            estadoActual = ap.obtenerEstado(i).getEstado(0);
            s = estadoActual.substring(estadoActual.length()-1);
            if (estadoActual.length()==1) ap.addTransicion(0,simb.indexOf(s),new Estado(estadoActual));
            else {
                estadoActual = estadoActual.substring(0,estadoActual.length()-1);
                indexEstado = ap.obtenerIndiceEstado(new Estado(estadoActual));
                ap.addTransicion(indexEstado,simb.indexOf(s),ap.obtenerEstado(i));
            }
        }
        apGenerado = true;
        if (esta==false) mpos.removeElement("%");
        bVerAP.setEnabled(true);
    }
    
    private void generaS() {
        if (sCalculado == false) {
            double max = -1;
            double stren = -1;
            Vector intersec = new Vector();
            Vector aux1 = new Vector();
            Vector aux2 = new Vector();
            Vector temp = new Vector();
            String t;

            cbValoresS.removeAllItems();
            if (apGenerado == false) generaAP();

            // Esto es para saber hasta que orden hay que calcular las T's
            int longMax = ap.obtenerEstado(0).getEstado(0).length();
            for (int i=1; i<ap.obtenerNumeroEstados(); i++)
                if ( ap.obtenerEstado(i).getEstado(0).length() > longMax )
                    longMax = ap.obtenerEstado(i).getEstado(0).length();

            for (int i=0; i<ap.obtenerNumeroEstados(); i++)
                for (int j=i; j<ap.obtenerNumeroEstados(); j++) {
                    if (i!=j) {
                        max = -1;
                        for (int valk=0; valk<=longMax; valk++) {
                            aux1 = AlgoritmoIM1.Tspos(ap,ap.obtenerEstado(i),valk);
                            aux2 = AlgoritmoIM1.Tspos(ap,ap.obtenerEstado(j),valk);
                            intersec = AlgoritmoIM1.interseccion(aux1,aux2);
                            float denominador = aux1.size()+aux2.size();
                            if (denominador!=0) stren = ((2*intersec.size())/denominador);
                            else stren = 0;
                            if (stren>max) max=stren;
                        } 
                        if (!temp.contains(Double.toString(max))) { //Para saber si el valor esta repe
                            temp.addElement(Double.toString(max));
                            cbValoresS.addItem(Double.toString(max));
                            if ((max>0) && (max<miclet)) miclet=max;
                        }
                    }
                }
            sCalculado = true;
        }        
    }
    
