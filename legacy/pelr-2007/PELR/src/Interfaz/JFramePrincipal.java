    private void jMenuItemValidarConjuntoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemValidarConjuntoActionPerformed
        Vector mValidar = new Vector();
        int buenas = 0;
        int malas = 0;
        boolean reconocida=false;
        boolean sigue=true;
        //Abrimos el fichero con las cadenas.
        try {
            JPanel panel = new JPanel(); 
            Cargar_fichero c = new Cargar_fichero(panel);
            
            String tF = c.filename;
            FileReader fr = new FileReader(tF);
            BufferedReader bw = new BufferedReader(fr);

            String t = bw.readLine();
            for (int i=0; t!=null; i++) {
                mValidar.addElement(t);
                t = bw.readLine();
            }
            //Si abre, comprobamos las cadenas.
            for (int n=0; n<mValidar.size(); n++) {
                Estado etemp = new Estado();
                Vector aux = new Vector();
                Vector aux2 = new Vector();
                String simbActual,cadActual,nombreEstado;

                aux2 = a.getSimbolos();
                nombreEstado = "";
                cadActual = mValidar.elementAt(n).toString();
                etemp = a.obtenerEstado(0);
                sigue=true;
                for (int i=0; (i<((String)mValidar.elementAt(n)).length()) && sigue; i++) {
                    simbActual = cadActual.substring(0,1);
                    nombreEstado = nombreEstado + simbActual;
                    cadActual = cadActual.substring(1);
                    try {
                        aux = (Vector)a.getTransicion(a.buscarEstado(etemp),aux2.indexOf(simbActual));
                        etemp = (Estado)aux.elementAt(0);
                        if (etemp.getTipoEstado().equals("FINAL")) reconocida=true;
                        else reconocida=false;
                    }
                    catch (Exception err) {
                        sigue=false;
                        reconocida=false;
                    }
                }
                if (reconocida) buenas++;
                else malas++;
            }
            float media = (float)malas / ((float)buenas+(float)malas);
            System.out.println(malas+" "+buenas+" "+media);
            JOptionPane.showMessageDialog(null,"Cadenas reconocidas: "+buenas+"\nCadenas no reconocidas: "+malas+"\n" +
                    "Porcentaje de errores: "+media*100+" %","Validar conjunto",JOptionPane.INFORMATION_MESSAGE);
        }
        catch (Exception err) {
            //Si no abre, se da error y se sale de la función.
	    JOptionPane.showMessageDialog(null,"Error al cargar muestra de test","Validar conjunto",JOptionPane.ERROR_MESSAGE);
	}
    }//GEN-LAST:event_jMenuItemValidarConjuntoActionPerformed

